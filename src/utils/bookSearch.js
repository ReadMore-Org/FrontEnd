export const normalizeSearch = value => String(value ?? '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
export const cleanSearch = value => String(value ?? '').trim().replace(/\s+/g, ' ');
export function searchISBN(value) {
  const isbn = cleanSearch(value).replace(/^isbn\s*:?\s*/i, '').replace(/[\s-]/g, '');
  return /^(\d{9}[\dXx]|\d{13})$/.test(isbn) ? isbn.toUpperCase() : null;
}
export function buildSearchSources(term, { languages = [], categories = [], orderBy = 'relevance' } = {}) {
  const text = cleanSearch(term);
  const selectedCategories = SEARCH_CATEGORIES.filter(item => categories.includes(item.value));
  const selectedLanguages = SEARCH_LANGUAGES.filter(item => languages.includes(item.value));
  if (!text && !selectedCategories.length) return [];
  const isbn = searchISBN(text);
  const base = isbn ? `isbn:${isbn}` : text;
  const sources = [];
  for (const category of selectedCategories.length ? selectedCategories : [null]) {
    for (const language of selectedLanguages.length ? selectedLanguages : [null]) {
      const subject = category ? `subject:"${category.value}"` : '';
      sources.push({ q: [base, subject].filter(Boolean).join(' ') || 'subject:fiction', langRestrict: language?.value, orderBy });
    }
  }
  // Busca no título complementa a busca geral, que também encontra autores.
  if (text && !isbn && !selectedCategories.length && !selectedLanguages.length && !/\w+:|"/.test(text) && orderBy === 'relevance') {
    sources.push({ q: `intitle:"${text.replace(/"/g, '')}"`, orderBy });
  }
  return sources.map(source => ({ ...source, startIndex: 0, done: false }));
}
export function buildTitleFallbackSources(term, options = {}) {
  const text = cleanSearch(term);
  if (!text || searchISBN(text) || /\w+:/.test(text)) return [];
  const stopwords = new Set(['o', 'a', 'os', 'as', 'um', 'uma', 'de', 'do', 'da', 'dos', 'das', 'e', 'the', 'of', 'and']);
  const words = normalizeSearch(text).split(' ').filter(word => word && !stopwords.has(word)).slice(0, 6);
  if (!words.length) return [];
  return buildSearchSources(words.map(word => `intitle:${word}`).join(' '), options);
}
export function matchesSearchFilters(book, languages = [], categories = [], { allowMissingCategories = false } = {}) {
  const language = book.idioma?.toLowerCase().split('-')[0];
  if (languages.length && !languages.includes(language)) return false;
  if (!categories.length) return true;
  const segments = [...(book.categorias_originais || []), ...(book.categorias || [])]
    .filter(value => typeof value === 'string')
    .flatMap(value => value.split('/')).map(normalizeSearch).filter(Boolean);
  if (!segments.length && allowMissingCategories) return true;
  // Compara segmentos inteiros: "Science Fiction" não é "Science",
  // e "Juvenile Nonfiction" não é "Fiction".
  return SEARCH_CATEGORIES.some(category => categories.includes(category.value)
    && category.aliases.some(alias => segments.includes(normalizeSearch(alias))));
}
export function mergeSearchBooks(books) {
  const seenIds = new Set();
  const seenISBNs = new Set();
  return books.filter(book => {
    if (!book.id || !book.titulo?.trim()) return false;
    const isbn = searchISBN(book.isbn);
    if (seenIds.has(book.id) || (isbn && seenISBNs.has(isbn))) return false;
    seenIds.add(book.id);
    if (isbn) seenISBNs.add(isbn);
    return true;
  });
}
export function sortSearchBooks(books, term, orderBy = 'relevance') {
  const text = normalizeSearch(term);
  const score = book => {
    const title = normalizeSearch(book.titulo);
    const authors = normalizeSearch((book.autores || []).map(author => typeof author === 'string' ? author : author.nome).join(' '));
    if (!text || searchISBN(term) || /\w+:/.test(term)) return 0;
    const companion = /\b(guide|guia|summary|resumo|unofficial|study|fanfiction)\b/.test(`${title} ${normalizeSearch(book.subtitulo)}`);
    const relevance = title === text || title.startsWith(text) ? 100 : title.includes(text) ? 60 : authors.includes(text) ? 50 : 0;
    return relevance - (companion ? 25 : 0);
  };
  return books.map((book, index) => ({ book, index })).sort((a, b) => {
    if (orderBy === 'newest') {
      const dateA = Date.parse(a.book.publicacao || '') || 0;
      const dateB = Date.parse(b.book.publicacao || '') || 0;
      return dateB - dateA || a.index - b.index;
    }
    const relevance = score(b.book) - score(a.book);
    if (relevance) return relevance;
    // Popularidade externa auxilia a descoberta; nunca vira nota do ReadMore.
    const popularity = book => Math.log10(Math.max(0, Number(book.popularidade_google) || 0) + 1) * 10
      + (Number(book.nota_google) || 0);
    return popularity(b.book) - popularity(a.book) || a.index - b.index;
  }).map(item => item.book);
}
